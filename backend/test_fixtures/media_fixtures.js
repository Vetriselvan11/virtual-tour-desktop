/**
 * Creates a valid MP3 audio file buffer.
 */
function createValidMp3() {
  // ID3v2.3 header (10 bytes) + title frame + MPEG-1 Layer III audio sync frames
  const id3Header = Buffer.from([
    0x49, 0x44, 0x33, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20
  ]);
  
  // Audio frame: 0xFF 0xFB (MPEG 1 Layer 3, 128kbps, 44100Hz, stereo, padded)
  const frameHeader = Buffer.from([0xFF, 0xFB, 0x90, 0x64]);
  const frameBody = Buffer.alloc(413, 0xAA); // 417 bytes total per 128k/44.1k frame

  const audioFrames = Buffer.concat([
    Buffer.concat([frameHeader, frameBody]),
    Buffer.concat([frameHeader, frameBody]),
    Buffer.concat([frameHeader, frameBody])
  ]);

  return Buffer.concat([id3Header, Buffer.alloc(32, 0), audioFrames]);
}

/**
 * Creates a valid MP4 video container buffer.
 */
function createValidMp4() {
  // ftyp box
  const ftyp = Buffer.from([
    0x00, 0x00, 0x00, 0x20, // size 32
    0x66, 0x74, 0x79, 0x70, // 'ftyp'
    0x69, 0x73, 0x6F, 0x6D, // major brand 'isom'
    0x00, 0x00, 0x02, 0x00, // minor version
    0x69, 0x73, 0x6F, 0x6D, // compatible brands: isom, iso2, avc1, mp41
    0x69, 0x73, 0x6F, 0x32,
    0x61, 0x76, 0x63, 0x31,
    0x6D, 0x70, 0x34, 0x31
  ]);

  // moov box (minimal)
  const moov = Buffer.from([
    0x00, 0x00, 0x00, 0x10, // size 16
    0x6D, 0x6F, 0x6F, 0x76, // 'moov'
    0x00, 0x00, 0x00, 0x08, // child box
    0x6D, 0x76, 0x68, 0x64  // 'mvhd'
  ]);

  // mdat box
  const mdat = Buffer.from([
    0x00, 0x00, 0x00, 0x10, // size 16
    0x6D, 0x64, 0x61, 0x74, // 'mdat'
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00
  ]);

  return Buffer.concat([ftyp, moov, mdat]);
}

/**
 * Creates a valid SVG vector icon buffer.
 */
function createValidSvg() {
  return Buffer.from(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">' +
    '<circle cx="50" cy="50" r="45" fill="#b88a44" stroke="#ffffff" stroke-width="4"/>' +
    '<polygon points="40,30 70,50 40,70" fill="#ffffff"/>' +
    '</svg>',
    'utf8'
  );
}

